import assert from 'node:assert/strict';
import { mergeConversationState, persistConversationState } from '../supabase/functions/_shared/waConversationState.ts';
const now = Date.now(), at = new Date(now).toISOString();
const initial = { sessions: { a: { state: 'idle' }, b: { state: 'idle' } }, humanPaused: { a: true }, testConsumed: { a: { username: 'old' } }, recentMsgIds: {}, botSendLog: [] };
const a = structuredClone(initial), b = structuredClone(initial);
a.sessions.a = { state: 'test_ask_name' }; delete a.humanPaused.a; delete a.testConsumed.a;
a.recentMsgIds['command-a'] = now + 60000; a.botSendLog.push({ phone: 'a', at });
b.sessions.b = { state: 'human' }; b.humanPaused.b = true;
b.recentMsgIds['command-b'] = now + 60000; b.botSendLog.push({ phone: 'b', at });
const currentA = mergeConversationState(initial, initial, a, now);
const currentAB = mergeConversationState(currentA, initial, b, now);
assert.equal(currentAB.sessions.a.state, 'test_ask_name');
assert.equal(currentAB.sessions.b.state, 'human');
assert.equal(currentAB.humanPaused.a, undefined); assert.equal(currentAB.humanPaused.b, true);
assert.equal(currentAB.testConsumed.a, undefined);
assert.deepEqual(Object.keys(currentAB.recentMsgIds).sort(), ['command-a', 'command-b']);
assert.equal(currentAB.botSendLog.length, 2);
const deletionBaseline = { sessions: { b: { state: 'old' } } };
assert.equal(mergeConversationState(currentAB, deletionBaseline, { sessions: {} }, now).sessions.b.state, 'human', 'stale cleanup cannot delete a new conversation');
assert.equal(mergeConversationState(currentAB, b, b, now).botSendLog.length, 2, 'repeat persistence cannot duplicate send history');
let saved, released = false;
const db = { from: () => ({ select: () => ({ eq: () => ({ maybeSingle: async () => ({ data: { value: currentA } }) }) }), upsert: async row => { saved = row.value; return {}; } }) };
const baseline = await persistConversationState(db, '1', initial, b, async () => ({ assertHeld() {}, release: async () => { released = true; } }));
assert.equal(saved.sessions.a.state, 'test_ask_name'); assert.equal(saved.sessions.b.state, 'human');
assert.equal(baseline.sessions.b.state, 'human'); assert.equal(released, true);
await assert.rejects(persistConversationState(db, '1', initial, b, async () => null), /ocupado/);
released = false;
const failing = { from: () => ({ select: () => ({ eq: () => ({ maybeSingle: async () => ({ error: Error('db unavailable') }) }) }) }) };
await assert.rejects(persistConversationState(failing, '1', initial, b, async () => ({ assertHeld() {}, release: async () => { released = true; } })), /ler estado/);
assert.equal(released, true, 'database failure releases the short account lock');
console.log('PASS: simultaneous chats preserve each other, owner release preserves other trials, stale deletion is safe, message IDs and send logs merge, short account lock is released on errors. No messages or payments.');
