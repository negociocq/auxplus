import assert from 'node:assert/strict';
import { EventEmitter } from 'node:events';
import vm from 'node:vm';
import { recoverOfflineDelivery, patchOfflineDelivery } from './evolution-offline-delivery.mjs';

let clock = 100000, next, calls = 0;
const ws = Object.assign(new EventEmitter(), { isOpen: true }), ev = new EventEmitter();
const socket = { ws, ev, sendNode: async node => { calls++; assert.equal(node.content[0].tag, 'offline_batch'); assert.equal(node.content[0].attrs.count, '100'); } };
const timers = { now: () => clock, setTimeout: fn => { next = fn; return 1; }, clearTimeout: () => { next = undefined; } };
const tick = async () => { const fn = next; next = undefined; await fn?.(); };
const recovery = recoverOfflineDelivery(socket, timers);
assert.equal(calls, 0, 'no immediate flood on connect');
await tick(); assert.equal(calls, 1, 'recover a stalled initial preview');
ws.emit('CB:message'); clock += 1000;
await tick(); assert.equal(calls, 1, 'do not add requests while delivery is advancing');
clock += 6000; await tick(); assert.equal(calls, 2, 'resume a stalled subsequent batch');
ev.emit('connection.update', { receivedPendingNotifications: true });
assert.equal(recovery.stats().stopped, true);
assert.equal(next, undefined, 'stop when the server confirms delivery completion');
assert.equal(ws.listenerCount('CB:message'), 0);
const capped = recoverOfflineDelivery(socket, { ...timers, maxRequests: 1 });
await tick(); await tick(); assert.equal(capped.stats().requests, 1);
assert.equal(capped.stats().stopped, true, 'recovery is bounded');
const closed = recoverOfflineDelivery(socket, timers);
ws.emit('close'); assert.equal(closed.stats().stopped, true);
const fixture = 'this.client=(0,R.default)(c),this.localSettings.wavoipToken';
const patched = patchOfflineDelivery(fixture);
new vm.Script(patched);
assert.equal(patchOfflineDelivery(patched), patched);
assert.match(patched, /auxplus-tarciocq1/);
assert.throws(() => patchOfflineDelivery('unknown'), /Unrecognized/);
console.log('PASS: recover stalled pending delivery, postpone while messages advance, stop on completion/close, bound retries, preserve account scope and patch syntax. No real messages sent.');
