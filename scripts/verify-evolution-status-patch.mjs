import assert from "node:assert/strict";
import { patchEvolutionStatus, marker } from "./evolution-status-single-upload.mjs";

const original = `async function sendMessage(e,t,l){if(e==="status@broadcast"){let u;t.status.option.allContacts?u=(await this.prismaRepository.contact.findMany({where:{instanceId:this.instanceId,remoteJid:{not:{endsWith:"@g.us"}}}})).map(w=>w.remoteJid):u=t.status.option.statusJidList;let m=10,d=Array.from({length:Math.ceil(u.length/m)},(S,w)=>u.slice(w*m,w*m+m)),h=null,g,f=d.shift();return f&&(g=await this.client.sendMessage(e,t.status.content,{backgroundColor:t.status.option.backgroundColor,font:t.status.option.font,statusJidList:f}),h=g.key.id),d.length===0||await Promise.allSettled(d.map(async S=>await this.client.sendMessage(e,t.status.content,{backgroundColor:t.status.option.backgroundColor,font:t.status.option.font,statusJidList:S,messageId:h}))),g}return await this.client.sendMessage(e,t,l)}`;
const patched = patchEvolutionStatus(original);
assert.ok(patched.includes(marker));
assert.equal(patchEvolutionStatus(patched), patched);
assert.throws(() => patchEvolutionStatus("unrecognized version"));
const fn = new Function(`return (${patched})`)();
const recipients = Array.from({ length: 2433 }, (_, i) => `551100${String(i).padStart(7, "0")}@s.whatsapp.net`);
const calls = [];
const context = { client: { sendMessage: async (...args) => { calls.push(args); return { key: { id: "test-status" } }; } }, prismaRepository: { contact: { findMany: async () => recipients.map(remoteJid => ({ remoteJid })) } } };
await fn.call(context, "status@broadcast", { status: { option: { statusJidList: [...recipients, recipients[0], "123456@g.us"] }, content: { image: { url: "https://example.com/banner.png" }, caption: "AuxPlus" } } });
assert.equal(calls.length, 1, "upload once, rather than once per ten contacts");
assert.equal(calls[0][2].statusJidList.length, 2433);
assert.equal(calls[0][2].broadcast, true);
assert.equal(calls[0][1].caption, "AuxPlus");
calls.length = 0;
context.client.user = { id: "5511999999999:7@s.whatsapp.net", lid: "123456789012345:7@lid" };
await fn.call(context, "status@broadcast", { status: { option: { statusJidList: recipients }, content: { text: "Own devices" } } });
assert.equal(calls.length, 1);
assert.ok(calls[0][2].statusJidList.includes("5511999999999@s.whatsapp.net"));
assert.ok(calls[0][2].statusJidList.includes("123456789012345@lid"));
assert.ok(!calls[0][2].statusJidList.some(jid => /:\d+@/.test(jid)), "normalize the sender's linked-device address");
calls.length = 0;
await fn.call(context, "status@broadcast", { status: { option: { allContacts: true }, content: { text: "Status" } } });
assert.equal(calls.length, 1);
calls.length = 0;
await fn.call(context, "5511000000000@s.whatsapp.net", { text: "Normal message" }, { quoted: "original" });
assert.equal(calls.length, 1); assert.deepEqual(calls[0][2], { quoted: "original" }, "normal messages retain their original path");
console.log("Evolution Status patch: single upload, owner PN/LID devices, audience deduplication, normal message isolation, version guard and rollback marker passed. No messages sent.");
