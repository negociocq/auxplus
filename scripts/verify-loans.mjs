import fs from 'node:fs';
import ts from 'typescript';
import assert from 'node:assert/strict';
const source = fs.readFileSync('src/lib/loans.ts', 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText;
const { loanBalance, readLoan, writeLoan, validateLoan, loanDueStatus, readLoanPixKey, writeLoanPixKey, readLoanReminder, writeLoanReminder, renderLoanReminder, DEFAULT_LOAN_REMINDER } = await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
const loan = { version: 1, principal: 1000, agreedAmount: 1100, lentAt: '2026-10-01', dueDate: '2026-11-09', lateRate: 3, latePeriod: 'month' };
assert.equal(loanBalance(loan, '2026-11-08').total, 1100);
assert.equal(loanBalance(loan, '2026-11-09').lateInterest, 0);
assert.equal(loanBalance(loan, '2026-11-10').lateInterest, 1.1);
assert.equal(loanBalance(loan, '2026-12-09').lateInterest, 33);
assert.equal(loanBalance(loan, '2027-01-08').lateInterest, 66, 'simple interest must not compound');
assert.equal(loanBalance({ ...loan, lateRate: 1, latePeriod: 'day' }, '2026-11-12').total, 1133);
assert.equal(loanBalance({ ...loan, lateRate: 0 }, '2027-11-09').total, 1100);
assert.equal(loanBalance({ ...loan, dueDate: '2028-02-28' }, '2028-03-01').daysLate, 2);
const paid = { ...loan, paidAt: '2026-11-12T12:00:00Z', paidAmount: 1103.3 };
assert.equal(loanBalance(paid, '2030-01-01').total, 1103.3);
assert.equal(loanBalance(paid, '2030-01-01').outstanding, 0);
const notes = writeLoan('Observações do cliente', loan);
assert.deepEqual(readLoan({ notes }), loan);
assert.deepEqual(readLoan({ notes: writeLoan(notes, paid) }), paid);
assert.equal(writeLoan(notes, paid).match(/<!--AXLOAN:/g).length, 1);
assert.equal(readLoan({ notes: '<!--AXLOAN:invalid-->' }), null);
assert.throws(() => validateLoan({ ...loan, dueDate: '2026-02-30' }));
assert.throws(() => validateLoan({ ...loan, dueDate: '2026-09-01' }));
assert.throws(() => validateLoan({ ...loan, lateRate: -1 }));
assert.throws(() => validateLoan({ ...loan, principal: NaN }));
assert.throws(() => validateLoan({ ...loan, agreedAmount: 900 }));
assert.equal(loanDueStatus('2026-11-14', '2026-11-10', 3), 'Longe de Vencer');
assert.equal(loanDueStatus('2026-11-13', '2026-11-10', 3), 'Perto de Vencer');
assert.equal(loanDueStatus('2026-11-10', '2026-11-10', 3), 'Perto de Vencer');
assert.equal(loanDueStatus('2026-11-09', '2026-11-10', 3), 'Já Vencido');
const message = 'Mensagem anterior preservada';
const pixSettings = writeLoanPixKey(message, ' pix+teste@example.com ');
assert.equal(readLoanPixKey(pixSettings), 'pix+teste@example.com');
assert.ok(pixSettings.startsWith(message));
assert.equal(readLoanPixKey(writeLoanPixKey(pixSettings, '5571999999999')), '5571999999999');
assert.equal(writeLoanPixKey(pixSettings, ''), message);
assert.equal(readLoanPixKey('outra pasta'), '');
assert.equal(readLoanPixKey('<!--AXLOANPIX:%ZZ-->'), '');
assert.throws(() => writeLoanPixKey('', 'a'.repeat(141)));
const customTemplate = 'Olá {name}, total {total}. PIX {pix}';
const configured = writeLoanReminder(pixSettings, customTemplate);
assert.equal(readLoanReminder(configured), customTemplate);
assert.equal(readLoanPixKey(configured), 'pix+teste@example.com');
assert.equal(readLoanReminder(writeLoanPixKey(configured, 'nova-chave')), customTemplate);
assert.equal(readLoanReminder('outra pasta'), DEFAULT_LOAN_REMINDER);
assert.equal(readLoanReminder('<!--AXLOANREMINDER:%ZZ-->'), DEFAULT_LOAN_REMINDER);
assert.equal(renderLoanReminder(customTemplate, { name: 'Ana {total}', total: 'R$ 500,00' }, 'chave'), 'Olá Ana {total}, total R$ 500,00. PIX chave');
assert.equal(renderLoanReminder('Olá {name}', { name: 'Ana' }, 'chave'), 'Olá Ana\n\nChave PIX para pagamento:\nchave');
assert.equal(renderLoanReminder('{name}', { name: 'Ana' }), 'Ana');
assert.throws(() => writeLoanReminder('', ' '));
assert.throws(() => writeLoanReminder('', 'a'.repeat(4001)));
console.log('PASS: due-day boundary, daily/monthly simple interest, leap days, zero rate, paid balance freeze, persisted terms, duplicate-marker removal and invalid terms.');
